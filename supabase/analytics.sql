--
-- 보안 원칙
--   · 공개(anon)는 INSERT 만. 읽기·수정·삭제는 열지 않는다.
--   · 보고서 스크립트는 아래 report_* 함수로만 읽는다.
--     함수는 토큰의 md5 가 맞을 때만 값을 돌려준다(토큰 원문은 노트북에만 있다).
--   · IP 원문은 저장하지 않는다. visitor = 하루 단위 해시(다음 날이면 바뀐다).
-- ============================================================

create table if not exists public.page_views (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kind text not null check (kind in ('page','nav','bot','click')),
  path text check (char_length(path) <= 300),
  ref_host text check (char_length(ref_host) <= 120),
  ref_path text check (char_length(ref_path) <= 300),
  utm_source text check (char_length(utm_source) <= 60),
  utm_medium text check (char_length(utm_medium) <= 60),
  utm_campaign text check (char_length(utm_campaign) <= 100),
  bot text check (char_length(bot) <= 40),
  device text check (char_length(device) <= 10),
  country text check (char_length(country) <= 4),
  region text check (char_length(region) <= 10),
  city text check (char_length(city) <= 60),
  visitor text check (char_length(visitor) <= 32),
  target text check (char_length(target) <= 300)
);
create index if not exists page_views_time_idx on public.page_views (created_at);

alter table public.page_views enable row level security;
drop policy if exists page_views_anon_insert on public.page_views;
create policy page_views_anon_insert on public.page_views
  for insert to anon, authenticated with check (true);
revoke select, update, delete on public.page_views from anon, authenticated;

-- 보고서 읽기(토큰 확인 후 기간 내 행을 1,000행씩)
create or replace function public.report_page_views(p_token text, p_since timestamptz, p_offset int default 0)
returns setof public.page_views
language plpgsql security definer set search_path = public as $$
begin
  if md5(coalesce(p_token,'')) <> '12532811effae8c7b18a0b06190e4d17' then
    raise exception 'denied';
  end if;
  return query
    select * from public.page_views
     where created_at >= p_since
     order by id
     offset greatest(p_offset,0) limit 1000;
end $$;

-- 문의 접수 건수(개인정보는 꺼내지 않고 날짜만)
create or replace function public.report_inquiry_dates(p_token text, p_since timestamptz)
returns table(created_at timestamptz)
language plpgsql security definer set search_path = public as $$
begin
  if md5(coalesce(p_token,'')) <> '12532811effae8c7b18a0b06190e4d17' then
    raise exception 'denied';
  end if;
  return query select i.created_at from public.inquiries i where i.created_at >= p_since order by 1;
end $$;

revoke all on function public.report_page_views(text, timestamptz, int) from public;
revoke all on function public.report_inquiry_dates(text, timestamptz) from public;
grant execute on function public.report_page_views(text, timestamptz, int) to anon;
grant execute on function public.report_inquiry_dates(text, timestamptz) to anon;
